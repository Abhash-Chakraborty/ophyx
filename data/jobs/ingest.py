CODE_LINE_RE = re.compile(r"^\s*(def |class |import |from \w+ import|for .+:|if .+:|return\b|print\(|>>> )", re.M)


def prog_score(text):
    words = re.findall(r"[a-z]+", text.lower())
    if not words:
        return 0.0
    hits = sum(w in PROG_WORDS for w in words)
    return 100.0 * hits / len(words) + 0.2 * min(20, len(CODE_LINE_RE.findall(text)))


