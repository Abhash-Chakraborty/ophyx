def notify(title, msg, tags="robot"):
    topic = KEYS.get("NTFY_TOPIC")
    if not topic:
        return
    try:
        req = urllib.request.Request(f"https://ntfy.sh/{topic}", data=msg.encode()[:3000],
                                     headers={"Title": title, "Tags": tags}, method="POST")
        urllib.request.urlopen(req, timeout=15)
    except Exception as e:  # notifications must never break the job
        log("ntfy failed:", e)


