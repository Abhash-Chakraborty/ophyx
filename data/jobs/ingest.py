class Uploader:
    """Buffers finished parts and commits them to HF in batches (HF limits commit rate)."""

    def __init__(self):
        self.pending = []
        self.api = None
        self.done = set()
        if not SMOKE:
            from huggingface_hub import HfApi
            self.api = HfApi(token=KEYS["HF_TOKEN"])
            self.api.create_repo(REPO, repo_type="dataset", private=True, exist_ok=True)
            self.done = set(self.api.list_repo_files(REPO, repo_type="dataset"))

    def exists(self, path_in_repo):
        return path_in_repo in self.done

    def add(self, local, path_in_repo):
        self.pending.append((local, path_in_repo))
        if len(self.pending) >= 16:
            self.flush()

    def flush(self):
        if not self.pending:
            return
        if SMOKE:
            for local, p in self.pending:
                log("smoke: would upload", p, os.path.getsize(local), "bytes")
            self.pending = []
            return
        from huggingface_hub import CommitOperationAdd
        ops = [CommitOperationAdd(path_in_repo=p, path_or_fileobj=local) for local, p in self.pending]
        for attempt in range(8):
            try:
                self.api.create_commit(REPO, repo_type="dataset", operations=ops,
                                       commit_message=f"{JOB} shard {SHARD}: {len(ops)} parts")
                break
            except Exception as e:
                wait = min(600, 30 * 2 ** attempt)
                log(f"commit failed ({type(e).__name__}: {str(e)[:200]}), retry in {wait}s")
                time.sleep(wait)
        else:
            raise RuntimeError("HF commit kept failing")
        for local, p in self.pending:
            self.done.add(p)
            if not SMOKE:
                os.remove(local)
        self.pending = []


def write_part(rows, name, uploader, stats):
    import pyarrow as pa
    import pyarrow.parquet as pq

    if not rows:
        return
    schema = pa.schema([(c, pa.string()) for c in ["id", "source", "repo", "path", "licence", "kind", "text", "text_raw"]]
                       + [("quality", pa.float64()), ("meta", pa.string())])
    table = pa.table({f.name: [r.get(f.name) for r in rows] for f in schema}, schema=schema)
    local = os.path.join(WORK, name.replace("/", "__"))
    pq.write_table(table, local, compression="zstd", compression_level=6)
    manifest_local = local + ".json"
    with open(manifest_local, "w") as f:
        json.dump(stats, f, indent=1)
    uploader.add(local, f"{PREFIX}/{name}")
    uploader.add(manifest_local, f"{PREFIX}/_manifests/{name}.json")


def sha1(t):
    return hashlib.sha1(t.encode("utf-8", "surrogatepass")).hexdigest()


def keep_raw_sample(h):
    return int(h[:4], 16) % 100 == 0  # 1% keep their pre-format text for the ablation


# ---------------------------------------------------------------- job: stack_edu

_tls = threading.local()


def _session():
    if not hasattr(_tls, "s"):
        import requests
        s = requests.Session()
        a = requests.adapters.HTTPAdapter(pool_connections=4, pool_maxsize=8, max_retries=3)
        s.mount("https://", a)
        _tls.s = s
    return _tls.s


def fetch_swh(blob_id, encoding):
    url = f"https://softwareheritage.s3.amazonaws.com/content/{blob_id}"
    for attempt in range(4):
        try:
            r = _session().get(url, timeout=30)
            if r.status_code == 200:
                raw = gzip.decompress(r.content)
                try:
                    return raw.decode(encoding or "utf-8")
                except (LookupError, UnicodeDecodeError):
                    return raw.decode("utf-8", errors="replace")
            if r.status_code in (403, 404):
                return None
        except Exception:
            pass
        time.sleep(1 + attempt * 2)
    return None


def _clean_stack_row(args):
    text, path, spdx = args
    return clean_code(text, path, spdx)


def job_stack_edu(uploader, pool):
    import pyarrow.parquet as pq

    CHUNK = 2_000 if SMOKE else 100_000
    if SMOKE:
        u = ("https://datasets-server.huggingface.co/rows?dataset=HuggingFaceTB/stack-edu"
             "&config=Python&split=train&offset=0&length=100")
        tok = os.environ.get("HF_TOKEN", "")
        req = urllib.request.Request(u, headers={"Authorization": f"Bearer {tok}", "User-Agent": "ophyx/0.1"})
        rows = [r["row"] for r in json.load(urllib.request.urlopen(req, timeout=60))["rows"]]
        files = [("smoke", rows)]
    else:
        from huggingface_hub import hf_hub_download
        files = []
        for i in range(5):
            p = hf_hub_download("HuggingFaceTB/stack-edu", f"Python/train-{i:05d}-of-00005.parquet",
                                repo_type="dataset", token=KEYS["HF_TOKEN"], cache_dir=os.path.join(WORK, "hf"))
            files.append((f"f{i}", p))

    chunk_idx = -1
    totals = {}
    for fname, src in files:
        if SMOKE:
            batches = [src]
        else:
            pf = pq.ParquetFile(src)
            cols = ["blob_id", "repo_name", "path", "src_encoding", "score", "int_score", "detected_licenses", "license_type"]
            batches = (b.to_pylist() for b in pf.iter_batches(batch_size=CHUNK, columns=cols))
        for batch in batches:
            chunk_idx += 1
            if chunk_idx % NSHARDS != SHARD:
                continue
            name = f"stack_edu/{fname}-c{chunk_idx:04d}.parquet"
            if uploader.exists(f"{PREFIX}/{name}"):
                log("skip existing", name)
                continue
            t = time.time()
            stats = {"input_rows": len(batch)}
            perm = []
            for r in batch:
                lic = [x.lower() for x in (r.get("detected_licenses") or [])]
                if SMOKE or (r.get("license_type") == "permissive" and lic and all(x in LICENCE_ALLOW for x in lic)):
                    perm.append(r)
            stats["licence_drop"] = len(batch) - len(perm)
            with cf.ThreadPoolExecutor(128) as ex:
                texts = list(ex.map(lambda r: fetch_swh(r["blob_id"], r.get("src_encoding")), perm))
            ok_rows = [(r, x) for r, x in zip(perm, texts) if x is not None]
            stats["fetch_fail"] = len(perm) - len(ok_rows)
            spdx_of = lambda r: (r.get("detected_licenses") or [None])[0]
            res = pool.map(_clean_stack_row, [(x, r["path"], spdx_of(r)) for r, x in ok_rows], chunksize=64)
            kept, seen = [], set()
            for (r, raw), (clean, reason, nred) in zip(ok_rows, res):
                stats[reason] = stats.get(reason, 0) + 1
                if clean is None:
                    continue
                h = sha1(clean)
                if h in seen:
                    stats["dup_in_chunk"] = stats.get("dup_in_chunk", 0) + 1
                    continue
                seen.add(h)
                kept.append({"id": h, "source": "stack_edu", "repo": r["repo_name"], "path": r["path"],
                             "licence": spdx_of(r), "kind": "code", "text": clean,
                             "text_raw": clean if keep_raw_sample(h) else None,
                             "quality": float(r.get("score") or 0),
                             "meta": json.dumps({"blob_id": r["blob_id"], "redactions": nred})})
            formatted = ruff_format([k["text"] for k in kept])
            okf = pool.map(_parse_ok, formatted, chunksize=64)
            for k, f, good in zip(kept, formatted, okf):
                if good:
                    k["text"] = f
                else:
                    stats["format_reverted"] = stats.get("format_reverted", 0) + 1
            stats["kept"] = len(kept)
            stats["kept_chars"] = sum(len(k["text"]) for k in kept)
            write_part(kept, name, uploader, stats)
            for k2, v in stats.items():
                totals[k2] = totals.get(k2, 0) + v
            log(f"{name}: {len(batch)} rows -> {len(perm)} permissive -> {len(kept)} kept "
                f"({stats['kept_chars'] / 1e6:.1f}M chars) in {time.time() - t:.0f}s")
            if SMOKE:
                break
    return totals


